import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const postsDirectory = path.join(projectRoot, 'content', 'posts');
const outputPath = path.join(projectRoot, 'content', 'posts.ts');

function readString(metadata, field, fileName, required = true) {
  const match = metadata.match(new RegExp(`\\b${field}:\\s*("(?:\\\\.|[^"\\\\])*")`));

  if (!match) {
    if (!required) return undefined;
    throw new Error(`${fileName}: post.${field} must be a double-quoted string`);
  }

  return JSON.parse(match[1]);
}

function readStringArray(metadata, field, fileName) {
  const match = metadata.match(new RegExp(`\\b${field}:\\s*(\\[[^\\]]*\\])`));
  if (!match) return [];

  const value = JSON.parse(match[1]);
  if (!Array.isArray(value) || value.some((item) => typeof item !== 'string')) {
    throw new Error(`${fileName}: post.${field} must be an array of strings`);
  }

  return value;
}

function parsePost(source, fileName) {
  const metadataMatch = source.match(/export const post\s*=\s*\{([\s\S]*?)\n\};/);
  if (!metadataMatch) throw new Error(`${fileName}: export const post metadata was not found`);

  const metadata = metadataMatch[1];
  const post = {
    slug: readString(metadata, 'slug', fileName),
    title: readString(metadata, 'title', fileName),
    description: readString(metadata, 'description', fileName),
    date: readString(metadata, 'date', fileName),
    image: readString(metadata, 'image', fileName, false),
    category: readString(metadata, 'category', fileName, false),
    tags: readStringArray(metadata, 'tags', fileName),
  };

  if (Number.isNaN(Date.parse(`${post.date}T00:00:00Z`))) {
    throw new Error(`${fileName}: post.date must use a valid YYYY-MM-DD value`);
  }

  return post;
}

function serializePost(post) {
  const optionalFields = [
    post.image ? `    image: ${JSON.stringify(post.image)},` : null,
    post.category ? `    category: ${JSON.stringify(post.category)},` : null,
    post.tags.length > 0 ? `    tags: ${JSON.stringify(post.tags)},` : '    tags: [],',
  ].filter(Boolean);

  return [
    '  {',
    `    slug: ${JSON.stringify(post.slug)},`,
    `    title: ${JSON.stringify(post.title)},`,
    `    description: ${JSON.stringify(post.description)},`,
    `    date: ${JSON.stringify(post.date)},`,
    ...optionalFields,
    '  },',
  ].join('\n');
}

const files = (await readdir(postsDirectory))
  .filter((fileName) => fileName.endsWith('.mdx'))
  .sort((a, b) => a.localeCompare(b, 'en'));

const entries = await Promise.all(
  files.map(async (fileName) => {
    const source = await readFile(path.join(postsDirectory, fileName), 'utf8');
    return { fileName, post: parsePost(source, fileName) };
  }),
);

const seenSlugs = new Map();
for (const { fileName, post } of entries) {
  const duplicate = seenSlugs.get(post.slug);
  if (duplicate) throw new Error(`Duplicate slug ${JSON.stringify(post.slug)} in ${duplicate} and ${fileName}`);
  seenSlugs.set(post.slug, fileName);
}

const sortedPosts = entries
  .map(({ post }) => post)
  .sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title, 'ko'));

const loaders = entries
  .map(({ fileName, post }) => `  ${JSON.stringify(post.slug)}: () => import('./posts/${fileName}'),`)
  .join('\n');

const output = `// This file is generated by scripts/generate-posts.mjs. Do not edit it directly.

export type PostSummary = {
  slug: string;
  title: string;
  description: string;
  date: string;
  image?: string;
  category?: string;
  tags: readonly string[];
};

export const postLoaders = {
${loaders}
} as const;

export type PostSlug = keyof typeof postLoaders;

export const posts = [
${sortedPosts.map(serializePost).join('\n')}
] as const satisfies readonly PostSummary[];
`;

await writeFile(outputPath, output);
console.log(`Generated ${entries.length} posts in ${path.relative(projectRoot, outputPath)}`);
